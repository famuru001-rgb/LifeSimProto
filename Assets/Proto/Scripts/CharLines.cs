        static void Add(CharProfile p, string key, params string[] v)
        {
            string[] old;
            if (p.lines.TryGetValue(key, out old))
            {
                var all = new List<string>(old);
                all.AddRange(v);
                p.lines[key] = all.ToArray();
            }
            else p.lines[key] = v;
        }

